#!/usr/bin/env node
/**
 * 生成ページを書き出す。
 *
 *   npm run docs:generate        （ルートから。先に `npm run build` が要る）
 *
 * 読むもの:
 *   dist/tools/definitions.js            ツール名・description・入力スキーマ
 *   src/server.ts                        INSTRUCTIONS（export されていないので正規表現で読む）
 *   tests/snapshot/cases.mjs             出力見本の呼び出し（ツール名 + 引数）
 *   tests/snapshot/__snapshots__/*.txt   出力見本の本文
 *
 * 書くもの（生成物。手で編集しない）:
 *   docs/reference/tools.md        docs/ja/reference/tools.md
 *   docs/reference/instructions.md docs/ja/reference/instructions.md
 *   docs/reference/examples.md     docs/ja/reference/examples.md
 */

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DOCS = path.join(HERE, '..');
const ROOT = path.join(DOCS, '..');

const REPO = 'https://github.com/shuji-bonji/rfcxml-mcp';
const RAW = 'https://raw.githubusercontent.com/shuji-bonji/rfcxml-mcp/main';
const SNAPSHOT_DIR = path.join(ROOT, 'tests', 'snapshot', '__snapshots__');
const EXAMPLE_HEAD_LINES = 60;

const BANNER = '<!-- generated by docs/scripts/generate.mjs — do not edit -->';

/** 表のセルに入れる文字列。`|` と改行を潰す。 */
function cell(value) {
  return String(value).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function code(value) {
  return `\`${String(value).replace(/`/g, '\\`')}\``;
}

/** JSON Schema の型を短く書く。`array` は要素の型を添える。 */
function typeOf(schema) {
  if (schema.type === 'array' && schema.items?.type) return `${schema.items.type}[]`;
  return schema.type ?? '';
}

