const EXAMPLES_TEXT = {
  en: {
    title: 'Output examples',
    intro: (n) =>
      `${n} calls fixed as output snapshots by \`npm run snapshot\` (\`tests/snapshot/cases.mjs\`). Each block is the recorded output for the call shown above it. Outputs longer than ${EXAMPLE_HEAD_LINES} lines are cut; the link opens the full file. \`<generatedAt>\` replaces the timestamp.`,
    args: 'Arguments',
    full: 'full output',
    truncated: (n) => `… (${n} lines)`,
  },
  ja: {
    title: '出力例',
    intro: (n) =>
      `\`npm run snapshot\`（\`tests/snapshot/cases.mjs\`）で固定している ${n} 件の呼び出しと、その出力です。各ブロックは、直前に示した呼び出しの実際の出力を記録したものです。${EXAMPLE_HEAD_LINES} 行を超える出力は途中で切っており、全文はリンク先で読めます。\`<generatedAt>\` は生成時刻を置き換えた印です。`,
    args: '引数',
    full: '全文',
    truncated: (n) => `… （全 ${n} 行）`,
  },
};

function fenceFor(text) {
  // 本文にバッククォートの連続があっても閉じないよう、最長の連続 + 1 で囲う
  const longest = Math.max(3, ...[...text.matchAll(/`+/g)].map((m) => m[0].length + 1));
  return '`'.repeat(longest);
}

async function renderExamples(cases, tools, lang) {
  const t = EXAMPLES_TEXT[lang];
  const out = [BANNER, '', `# ${t.title}`, '', t.intro(cases.length), ''];

  const byTool = new Map();
  for (const c of cases) {
    if (!byTool.has(c.tool)) byTool.set(c.tool, []);
    byTool.get(c.tool).push(c);
  }
  // definitions.js の順に並べ、載っていないツールは末尾
  const order = [...tools.map((x) => x.name), ...byTool.keys()].filter(
    (name, i, arr) => byTool.has(name) && arr.indexOf(name) === i
  );

  for (const toolName of order) {
    out.push(`## ${toolName}`, '');
    for (const c of byTool.get(toolName)) {
      const file = path.join(SNAPSHOT_DIR, `${c.name}.txt`);
      const text = (await fs.readFile(file, 'utf8')).replace(/\s+$/, '');
      const lines = text.split('\n');
      const rawUrl = `${RAW}/tests/snapshot/__snapshots__/${c.name}.txt`;
      out.push(`### ${c.name}`, '');
      out.push(`${t.args}: ${code(c.tool)}`, '', '```json', JSON.stringify(c.args, null, 2), '```', '');
      const fence = fenceFor(text);
      if (lines.length > EXAMPLE_HEAD_LINES) {
        out.push(
          `${fence}text`,
          ...lines.slice(0, EXAMPLE_HEAD_LINES),
          t.truncated(lines.length),
          fence,
          ''
        );
      } else {
        out.push(`${fence}text`, ...lines, fence, '');
      }
      out.push(`[${t.full}](${rawUrl}) (${lines.length} lines)`, '');
    }
  }
  return out.join('\n');
}

// ---------------------------------------------------------------------------

async function main() {
  const definitions = await import(path.join(ROOT, 'dist', 'tools', 'definitions.js'));
  const tools = definitions.tools ?? definitions.TOOL_DEFINITIONS;
  if (!Array.isArray(tools)) throw new Error('dist/tools/definitions.js に tools が無い');
  const { CASES } = await import(path.join(ROOT, 'tests', 'snapshot', 'cases.mjs'));
  const instructions = await readInstructions();

  const files = [
    ['reference/tools.md', renderTools(tools, 'en')],
    ['ja/reference/tools.md', renderTools(tools, 'ja')],
    ['reference/instructions.md', renderInstructions(instructions, 'en')],
    ['ja/reference/instructions.md', renderInstructions(instructions, 'ja')],
    ['reference/examples.md', await renderExamples(CASES, tools, 'en')],
    ['ja/reference/examples.md', await renderExamples(CASES, tools, 'ja')],
  ];
  for (const [rel, content] of files) {
    const target = path.join(DOCS, rel);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, content);
    console.log(`wrote docs/${rel}`);
  }
  console.log(`tools: ${tools.length}, cases: ${CASES.length}`);
}

await main();
