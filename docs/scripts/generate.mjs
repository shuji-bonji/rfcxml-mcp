async function readInstructions() {
  const source = await fs.readFile(path.join(ROOT, 'src', 'server.ts'), 'utf8');
  const match = source.match(/const INSTRUCTIONS = `([\s\S]*?)`;/);
  if (!match) throw new Error('src/server.ts に INSTRUCTIONS が見つからない');
  // テンプレートリテラルの中でエスケープしたバッククォートを戻す
  return match[1].replace(/\\`/g, '`');
}

const INSTRUCTIONS_TEXT = {
  en: {
    title: 'Server instructions',
    intro:
      'The text below is what the server hands to the MCP client as `instructions` at initialization. It is the same text the client model sees. Generated from `src/server.ts`.',
  },
  ja: {
    title: 'サーバーの instructions',
    intro:
      '接続の初期化時に、サーバーが MCP クライアントへ `instructions` として渡す説明文です。クライアント側のモデルが受け取るものと同じ文面で、`src/server.ts` から生成しています（英語のまま）。',
  },
};

function renderInstructions(text, lang) {
  const t = INSTRUCTIONS_TEXT[lang];
  return [BANNER, '', `# ${t.title}`, '', t.intro, '', '````text', text.trim(), '````', ''].join('\n');
}

