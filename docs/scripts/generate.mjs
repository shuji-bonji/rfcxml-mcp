const TOOLS_TEXT = {
  en: {
    title: 'Tools',
    intro:
      'Seven tools. Every input schema has `additionalProperties: false`: an unknown key (for example `sections` where `section` is expected) is rejected by the SDK input validation with `isError: true`, not silently ignored.',
    source: 'Generated from `dist/tools/definitions.js`.',
    parameters: 'Parameters',
    none: 'No parameters.',
    head: ['Name', 'Type', 'Required', 'Default', 'Enum', 'Constraints', 'Description'],
    yes: 'yes',
    no: 'no',
    additional: 'Unknown keys are rejected (`additionalProperties: false`).',
  },
  ja: {
    title: 'ツール',
    intro:
      'このサーバーには 7 つのツールがあります。すべてのツールの入力スキーマに `additionalProperties: false` が指定されているため、定義されていないキー（たとえば `section` のつもりで `sections` を渡した場合）は SDK の入力検証で `isError: true` になり、黙って無視されることはありません。',
    source: 'このページは `dist/tools/definitions.js` から生成しています。各ツールの説明文は、クライアントのモデルが受け取るものと同じ英語のままにしています。',
    parameters: 'パラメータ',
    none: 'パラメータはありません。',
    head: ['名前', '型', '必須', '既定値', 'enum', '制約', '説明'],
    yes: 'はい',
    no: 'いいえ',
    additional: '定義されていないキーは受け付けません（`additionalProperties: false`）。',
  },
};

function renderTools(tools, lang) {
  const t = TOOLS_TEXT[lang];
  const out = [BANNER, '', `# ${t.title}`, '', t.intro, '', t.source, ''];

  out.push('| | |', '|---|---|');
  for (const tool of tools) {
    out.push(`| [${code(tool.name)}](#${tool.name.replace(/_/g, '-')}) | ${cell(tool.description)} |`);
  }
  out.push('');

  for (const tool of tools) {
    const schema = tool.inputSchema;
    const required = new Set(schema.required ?? []);
    out.push(`## ${tool.name}`, '', tool.description, '', `### ${t.parameters}`, '');
    const entries = Object.entries(schema.properties ?? {});
    if (entries.length === 0) {
      out.push(t.none, '');
    } else {
      out.push(`| ${t.head.join(' | ')} |`, `|${t.head.map(() => '---').join('|')}|`);
      for (const [name, prop] of entries) {
        const constraints = [];
        if (prop.minLength !== undefined) constraints.push(`minLength: ${prop.minLength}`);
        if (prop.maxLength !== undefined) constraints.push(`maxLength: ${prop.maxLength}`);
        if (prop.minimum !== undefined) constraints.push(`minimum: ${prop.minimum}`);
        if (prop.maximum !== undefined) constraints.push(`maximum: ${prop.maximum}`);
        if (prop.pattern !== undefined) constraints.push(`pattern: ${code(prop.pattern)}`);
        out.push(
          `| ${[
            code(name),
            code(typeOf(prop)),
            required.has(name) ? t.yes : t.no,
            prop.default === undefined ? '' : code(JSON.stringify(prop.default)),
            prop.enum ? prop.enum.map((v) => code(v)).join(', ') : '',
            constraints.join(', '),
            cell(prop.description ?? ''),
          ].join(' | ')} |`
        );
      }
      out.push('');
    }
    out.push(
      schema.additionalProperties === false
        ? t.additional
        : `\`additionalProperties: ${JSON.stringify(schema.additionalProperties)}\``,
      ''
    );
  }
  return out.join('\n');
}

